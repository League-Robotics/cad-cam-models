"""Pick sprue bars for scad/swap_plate.scad.

Reads the part placements from swap_plate.scad, takes each STL's bed-contact
outline (vertices on z = 0), and joins neighbouring parts with short bars at
their closest points: every pair closer than NEAR gets bars every SPACING mm
along the shared edge, and a minimum spanning tree over all parts makes sure
the whole plate is one connected piece. Writes scad/swap_plate_sprues.scad.
Run from anywhere: python3 tools/plate_sprues.py
"""
import math, os, re, struct, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

NEAR = 12.0      # join pairs whose outlines come this close
SLACK = 6.0      # extra bars where the gap is within this of the closest
SPACING = 8.0    # min distance between bars on the same pair
STEP = 1.0       # resample outlines to this spacing

src = open(os.path.join(ROOT, "scad/swap_plate.scad")).read()
nub_bb = eval(re.search(r"nub_bb = (\[\[.*?\]\]);", src).group(1))
rows = re.findall(r'\["([\w/]+)",\s*(nub_bb|\[\[.*?\]\]),\s*(\[[-\d., ]+\]),\s*(-?\d+)\]', src)

def load(name):
    d = open(os.path.join(ROOT, f"grippers/{name}.stl"), "rb").read()
    v = [tuple(map(float, m)) for m in re.findall(rb"vertex\s+(\S+)\s+(\S+)\s+(\S+)", d)]
    tris = [v[i:i + 3] for i in range(0, len(v), 3)]
    # bottom-face triangles; their edges used once are the outline
    edges = {}
    for t in tris:
        if all(abs(p[2]) < 1e-3 for p in t):
            for a, b in ((t[0], t[1]), (t[1], t[2]), (t[2], t[0])):
                k = tuple(sorted((a[:2], b[:2])))
                edges[k] = edges.get(k, 0) + 1
    pts = []
    for (a, b), c in edges.items():
        if c != 1:
            continue
        n = max(1, int(math.dist(a, b) / STEP))
        pts += [(a[0] + (b[0] - a[0]) * i / n, a[1] + (b[1] - a[1]) * i / n) for i in range(n)]
    return pts

parts = []
for name, bb, pos, rot in rows:
    bb = nub_bb if bb == "nub_bb" else eval(bb)
    pos = eval(pos); r = math.radians(float(rot))
    cx, cy = (bb[0][0] + bb[0][1]) / 2, (bb[1][0] + bb[1][1]) / 2
    c, s = math.cos(r), math.sin(r)
    pts = [(pos[0] + c * (x - cx) - s * (y - cy), pos[1] + s * (x - cx) + c * (y - cy)) for x, y in load(name)]
    parts.append((name, pts))
    print(f"{name:18s} {len(pts):5d} outline pts", file=sys.stderr)

def pairs(a, b):
    out = []
    for p in a:
        q = min(b, key=lambda q: (q[0] - p[0]) ** 2 + (q[1] - p[1]) ** 2)
        out.append((math.dist(p, q), p, q))
    return sorted(out)

n = len(parts)

def seg_dist(p, a, b):
    ab = (b[0] - a[0], b[1] - a[1]); l2 = ab[0] ** 2 + ab[1] ** 2
    t = max(0, min(1, ((p[0] - a[0]) * ab[0] + (p[1] - a[1]) * ab[1]) / l2)) if l2 else 0
    return math.dist(p, (a[0] + t * ab[0], a[1] + t * ab[1]))

def crosses_other(p, q, k):
    """True if the bar p-q passes within 1.5 mm of a part it doesn't join."""
    return any(seg_dist(r, p, q) < 1.5 for m in range(n) if m not in k for r in parts[m][1])

cand = {}
for i in range(n):
    for j in range(i + 1, n):
        cand[(i, j)] = pairs(parts[i][1], parts[j][1])

# minimum spanning tree on closest distance
dist = {k: v[0][0] for k, v in cand.items() if not crosses_other(v[0][1], v[0][2], k)}
tree, seen = set(), {0}
while len(seen) < n:
    k = min((k for k in dist if (k[0] in seen) != (k[1] in seen)), key=dist.get)
    tree.add(k); seen |= set(k)

bars = []
for k, lst in cand.items():
    d0 = lst[0][0]
    if d0 > NEAR and k not in tree:
        continue
    chosen = []
    for d, p, q in lst:
        if d > d0 + SLACK or d > max(NEAR, d0):
            break
        mid = ((p[0] + q[0]) / 2, (p[1] + q[1]) / 2)
        if all(math.dist(mid, m) >= SPACING for m in chosen) and not crosses_other(p, q, k):
            chosen.append(mid)
            bars.append((p, q, parts[k[0]][0], parts[k[1]][0], d))
    print(f"{parts[k[0]][0]:18s} - {parts[k[1]][0]:18s} gap {d0:5.1f}  bars {len(chosen)}{'  (tree)' if k in tree else ''}", file=sys.stderr)

with open(os.path.join(ROOT, "scad/swap_plate_sprues.scad"), "w") as f:
    f.write("// Generated by tools/plate_sprues.py from swap_plate.scad: sprue bars\n")
    f.write("// [[x, y] on one part's edge, [x, y] on the neighbour's edge]\n")
    f.write("SPRUES = [\n")
    for p, q, a, b, d in bars:
        f.write(f"  [[{p[0]:.2f}, {p[1]:.2f}], [{q[0]:.2f}, {q[1]:.2f}]],  // {a} - {b}, {d:.1f}\n")
    f.write("];\n")
print(len(bars), "bars", file=sys.stderr)
